import { createServer } from 'node:http';
import { loadConfig, appRoot } from './config';
import { LocalDemoMemory } from './memory';
import { MockNimoServiceNow } from './nimo';
import { OpenAIResponses } from './openai';
import { HRSession } from './agent';
import { createApp } from './app';
import { attachRelay, RelayRegistry } from './relay';
const config=loadConfig();
const memory=new LocalDemoMemory(appRoot+'.demo-data/rafael.json');
const nimo=new MockNimoServiceNow();
const provider=config.aiEnabled&&config.apiKey&&config.model?new OpenAIResponses({apiKey:config.apiKey,model:config.model}):undefined;
const factory=async(mode:'demo'|'voice'='demo')=>{const s=await new HRSession(memory,nimo,provider,mode).init();s.state.integrations.tts=`${config.voice.ttsProvider} · ${config.voice.ttsLanguage} · voz ${config.voice.voice.split('-')[0]} · frases completas`;return s;};
let session=await factory();
const registry=new RelayRegistry(()=>factory('voice'));
const setSession=(s:HRSession)=>{session=s;};
const app=createApp({...config,session,registry,getSession:()=>session,createSession:()=>factory(),setSession,staticDir:appRoot+'dist'});
const server=createServer(app);const wss=attachRelay(server,{...config,ttsLanguage:config.voice.ttsLanguage,registry,onSession:setSession});
server.listen(config.port,'127.0.0.1',()=>console.info('Globo RH Demo: http://127.0.0.1:3007/globo/ · public panel requires authentication'));
server.on('error',()=>{console.error('Globo: não foi possível iniciar o servidor local.');process.exitCode=1;});
for(const signal of ['SIGINT','SIGTERM'] as const)process.on(signal,()=>{session.finish('Servidor encerrado.');for(const ws of wss.clients)ws.close(1001);wss.close();server.close();});
